package co.ritech.news;

import java.math.BigDecimal;
import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.util.List;

import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Component;

/** Sample feed for development, demos and CI: no external calls, stable URLs (deduplicated). */
@Component
@ConditionalOnProperty(name = "ritech.news.provider", havingValue = "fixed", matchIfMissing = true)
public class FixedNewsProvider implements NewsProvider {

    static final String BASE_URL = "https://example.com/ritech-demo/news/";

    private final Clock clock;

    public FixedNewsProvider(Clock clock) {
        this.clock = clock;
    }

    @Override
    public List<NewsItem> fetchLatest(String tickers) {
        Instant now = clock.instant();
        return List.of(
                item(1, "Tech stocks lift the Nasdaq 100 on strong earnings", "0.3000", "Somewhat-Bullish", now, 1),
                item(2, "Investors await the Federal Reserve rate decision", "0.0500", "Neutral", now, 2),
                item(3, "Chipmakers slip as supply concerns return", "-0.2000", "Somewhat-Bearish", now, 3));
    }

    @Override
    public boolean quotaLimited() {
        return false;
    }

    private static NewsItem item(int n, String title, String score, String label, Instant now, int hoursAgo) {
        return new NewsItem(
                BASE_URL + n,
                title,
                "Demo article generated by the fixed news provider.",
                "RiTech demo",
                now.minus(Duration.ofHours(hoursAgo)),
                new BigDecimal(score),
                label);
    }
}
